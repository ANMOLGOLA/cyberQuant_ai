// Reusable standard controls
const createControl = (
  id: string,
  name: string,
  category: SecurityControl['category'],
  status: 'Full' | 'Partial' | 'Missing',
  config: number,
  history: number,
  compliance: number,
  frameworks: string[]
): SecurityControl => ({
  id,
  name,
  category,
  implementationStatus: status,
  configurationStrength: config,
  incidentHistoryScore: history,
  complianceScore: compliance,
  effectiveness: Number(((config * 0.45 + history * 0.25 + compliance * 0.3) * (status === 'Full' ? 1.0 : status === 'Partial' ? 0.6 : 0.15)).toFixed(3)),
  frameworks,
});

